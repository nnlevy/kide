// Generate the browser's voice registry from the same manifest that renders
// and publishes the MP3 pack. Runtime ids, fallback text, pack version, and
// published files therefore have one source of truth.

import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const manifest = require(join(here, 'manifest.js'));
const out = join(root, 'public', 'voice-manifest.js');
const packIndex = join(root, 'public', 'voice', manifest.packVersion, 'index.json');

const lines = Object.create(null);
for (const line of manifest.lines) {
  if (!line?.id || !line?.text) throw new Error('every voice line needs an id and fallback text');
  if (lines[line.id]) throw new Error(`duplicate voice id: ${line.id}`);
  lines[line.id] = line.text;
}

if (!existsSync(packIndex)) throw new Error(`published voice index is missing: ${packIndex}`);
const published = JSON.parse(readFileSync(packIndex, 'utf8'));
if (published.version !== manifest.packVersion) {
  throw new Error(`voice pack version ${published.version} does not match manifest ${manifest.packVersion}`);
}
const publishedIds = new Set(published.ids || []);
const missing = Object.keys(lines).filter((id) => !publishedIds.has(id));
const stale = [...publishedIds].filter((id) => !lines[id]);
if (missing.length || stale.length) {
  throw new Error(`voice registry/pack drift: missing=${missing.join(',')} stale=${stale.join(',')}`);
}

const registry = {
  packVersion: manifest.packVersion,
  voice: manifest.voice,
  model: manifest.model,
  lines,
};
const source = `/* GENERATED by tools/voice/build-browser-registry.mjs. Do not edit. */\n`
  + `(function(g){g.KideVoiceRegistry=Object.freeze(${JSON.stringify(registry)});})(window);\n`;
writeFileSync(out, source);
console.log(`browser voice registry: ${Object.keys(lines).length} lines -> ${out}`);
